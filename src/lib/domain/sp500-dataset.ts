/**
 * Retorna os 50 componentes mais líquidos com cotação spot <= $150.00
 * Prioriza ativos com rating de liquidez 4 e 5 e IV Rank atraente.
 */
export function getTop50LiquidUnder150(): SP500StockData[] {
  return SP500_DATASET
    .filter(stock => stock.spot <= 150.00)
    .sort((a, b) => {
      // 1º Critério: Liquidez de opções (rating 5 primeiro)
      if (b.liquidityRating !== a.liquidityRating) {
        return b.liquidityRating - a.liquidityRating;
      }
      // 2º Critério: Volume médio de contratos
      if (b.avgOptionVolume !== a.avgOptionVolume) {
        return b.avgOptionVolume - a.avgOptionVolume;
      }
      // 3º Critério: IV Rank descrescente
      return b.ivr - a.ivr;
    })
    .slice(0, 50);
}

/**
 * Busca ultrarrápida indexada em todo o universo S&P 500 por ticker ou nome da empresa.
 */
export function searchSP500(query: string): SP500StockData[] {
  const clean = query.trim().toUpperCase();
  if (!clean) return SP500_DATASET;

  return SP500_DATASET.filter(stock => 
    stock.symbol.toUpperCase().includes(clean) || 
    stock.name.toUpperCase().includes(clean) ||
    stock.sector.toUpperCase().includes(clean)
  );
}

